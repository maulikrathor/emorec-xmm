"""Shared fixtures for the MELD data-pipeline tests.

Every fixture here is safe on a machine with no MELD data. `tiny_mp4` needs
ffmpeg and is only ever requested by tests marked
`@pytest.mark.skipif(not shutil.which("ffmpeg"), ...)`; it also defends
itself with `pytest.skip` if somehow called without ffmpeg present.
`toy_meld_root` uses placeholder (non-ffmpeg) `.mp4` files since path/media
resolution tests only need the right filenames to exist, not real video
content.
"""

import shutil
import subprocess
from pathlib import Path

import pandas as pd
import pytest

HAS_FFMPEG = shutil.which("ffmpeg") is not None

# Real MELD CSV column order (11 columns).
MELD_COLUMNS = [
    "Sr No.",
    "Utterance",
    "Speaker",
    "Emotion",
    "Sentiment",
    "Dialogue_ID",
    "Utterance_ID",
    "Season",
    "Episode",
    "StartTime",
    "EndTime",
]


@pytest.fixture
def has_ffmpeg() -> bool:
    return HAS_FFMPEG


@pytest.fixture
def tiny_mp4(tmp_path: Path) -> Path:
    """A real ~1.5 s A/V .mp4 generated by ffmpeg, for extract_wav/loudness tests."""
    if not HAS_FFMPEG:
        pytest.skip("ffmpeg not installed")
    out = tmp_path / "dia0_utt0.mp4"
    cmd = [
        "ffmpeg", "-y", "-v", "error",
        "-f", "lavfi", "-i", "sine=frequency=440:duration=1.5",
        "-f", "lavfi", "-i", "testsrc=duration=1.5:size=64x64:rate=10",
        "-shortest", "-pix_fmt", "yuv420p",
        str(out),
    ]
    subprocess.run(cmd, capture_output=True, text=True, check=True)
    return out


def _write_csv(path: Path, rows: list[list], columns: list[str] = MELD_COLUMNS) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows, columns=columns).to_csv(path, index=False)


def _touch_mp4(directory: Path, dialogue_id: int, utterance_id: int) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / f"dia{dialogue_id}_utt{utterance_id}.mp4").write_bytes(b"placeholder-not-a-real-mp4")


def _touch_appledouble(directory: Path, dialogue_id: int, utterance_id: int) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / f"._dia{dialogue_id}_utt{utterance_id}.mp4").write_bytes(b"\x00\x05\x16\x07")


